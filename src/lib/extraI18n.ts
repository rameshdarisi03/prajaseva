/**
 * Dynamically scales text size class based on character length so longer Indian-language labels
 * fit cleanly inside buttons, badges, and milestone headers without clipping or overflowing.
 */
export function fitTextClass(text: string | undefined | null, base: 'xs' | 'sm' = 'xs'): string {
  const len = (text || '').trim().length;
  if (base === 'sm') {
    if (len > 30) return 'text-[10px] leading-tight';
    if (len > 20) return 'text-[11px] leading-tight';
    return 'text-xs sm:text-sm leading-snug';
  }
  if (len > 28) return 'text-[9.5px] leading-tight';
  if (len > 18) return 'text-[10.5px] leading-tight';
  return 'text-xs leading-snug';
}
